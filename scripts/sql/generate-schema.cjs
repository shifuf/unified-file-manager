#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '../..');
const schemaPath = path.join(root, 'apps/api/prisma/schema.prisma');
const migrationsPath = path.join(root, 'apps/api/prisma/migrations');
const hash = value => createHash('sha256').update(value).digest('hex');
const normalize = value => value.toString('utf8').replace(/\r\n/g, '\n');

function main(args) {
  let outputDir = __dirname;
  let check = false;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--check') check = true;
    else if (args[index] === '--output-dir') {
      const value = args[++index];
      if (!value || value.startsWith('--')) throw new Error('--output-dir requires a directory');
      outputDir = path.resolve(value);
    } else throw new Error(`Unknown argument: ${args[index]}`);
  }

  const prismaPackagePath = require.resolve('prisma/package.json', { paths: [root] });
  const prismaPackage = JSON.parse(fs.readFileSync(prismaPackagePath, 'utf8'));
  const prismaCli = path.join(path.dirname(prismaPackagePath), 'build/index.js');
  const generated = spawnSync(process.execPath, [prismaCli, 'migrate', 'diff',
    '--from-empty', '--to-schema-datamodel', schemaPath, '--script'], {
    cwd: root, encoding: 'utf8', windowsHide: true, timeout: 90000,
    env: { ...process.env, CHECKPOINT_DISABLE: '1', PRISMA_HIDE_UPDATE_MESSAGE: 'true' },
    maxBuffer: 8 * 1024 * 1024,
  });
  if (generated.error || generated.status !== 0) {
    // Do not print Prisma stderr: environment/connection diagnostics may contain secrets.
    throw new Error(`Prisma schema generation failed (${generated.error?.code ?? generated.status}). Check local Prisma engine availability.`);
  }
  const body = generated.stdout.replace(/\r\n/g, '\n').trim();
  if (!body.startsWith('--') || !body.includes('CREATE TABLE')) throw new Error('Prisma did not return schema SQL');
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  const sql = `-- Unified File Manager v${version}: current schema snapshot (MySQL).\n`
    + '-- EMPTY DATABASE ONLY. Existing installations: npm --workspace apps/api run db:deploy\n'
    + '-- This file is not an incremental migration and does not record Prisma migration history.\n'
    + '-- See scripts/sql/README.md before importing. Generated by npm run db:sql.\n\n'
    + `${body}\n`;
  const names = fs.readdirSync(migrationsPath, { withFileTypes: true })
    .filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
  const manifest = {
    formatVersion: 1,
    applicationVersion: version,
    prismaVersion: prismaPackage.version,
    sourceLineEndings: 'LF',
    schemaSha256: hash(normalize(fs.readFileSync(schemaPath))),
    sqlSha256: hash(sql),
    migrations: names.map(name => ({ name, sha256: hash(normalize(fs.readFileSync(path.join(migrationsPath, name, 'migration.sql')))) })),
  };
  const outputs = [['schema.sql', sql], ['manifest.json', `${JSON.stringify(manifest, null, 2)}\n`]];
  if (check) {
    const stale = outputs.filter(([name, value]) => {
      const file = path.join(outputDir, name);
      return !fs.existsSync(file) || normalize(fs.readFileSync(file)) !== value;
    });
    if (stale.length) throw new Error(`SQL distribution is out of date: ${stale.map(([name]) => name).join(', ')}. Run npm run db:sql.`);
    console.log('SQL distribution matches the current schema and migration history.');
    return;
  }
  fs.mkdirSync(outputDir, { recursive: true });
  for (const [name, value] of outputs) fs.writeFileSync(path.join(outputDir, name), value);
  console.log(`Generated schema.sql and manifest.json (${names.length} preserved migrations).`);
}

try { main(process.argv.slice(2)); }
catch (error) { console.error(error.message); process.exitCode = 1; }
