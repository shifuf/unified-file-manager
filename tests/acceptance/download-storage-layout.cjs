/* Real retained files and Chrome. Does not change bindings or delete files. */
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/shifuf/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '../..'), base = process.env.UFM_TEST_BASE || 'http://localhost:5175';
const latest = JSON.parse(fs.readFileSync(path.join(root, '.runtime/acceptance-20261114-storage-ui/local-latest.json'), 'utf8'));
const out = path.join(root, '.runtime/acceptance-20261114-download-layout');
fs.mkdirSync(out, { recursive: true });
const report = { base, checks: [], screenshots: [], retainedProject: latest.project.id };
const check = (name, evidence) => { report.checks.push({ name, pass: true, evidence }); console.log(JSON.stringify({ name, pass: true })); };
let browser, context;
(async () => { try {
  const env = Object.fromEntries(fs.readFileSync(path.join(root, '.env'), 'utf8').split(/\r?\n/).filter(s => /^\w+=/.test(s)).map(s => { const i = s.indexOf('='); return [s.slice(0, i), s.slice(i + 1).trim().replace(/^['"]|['"]$/g, '')]; }));
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  context = await browser.newContext({ viewport: { width: 1560, height: 800 }, userAgent: 'UFM-Download-Storage-Layout-Acceptance' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const navigate = target => page.evaluate(target => document.querySelector('#app').__vue_app__.config.globalProperties.$router.push(target), target);
  const screenshot = async name => { const file = path.join(out, name + '.png'); await page.screenshot({ path: file, fullPage: true }); report.screenshots.push(file); };
  await page.goto(base + (env.ADMIN_LOGIN_PATH || '/console-login'));
  await page.locator('input[autocomplete="username"]').fill(env.ADMIN_USERNAME);
  await page.locator('input[autocomplete="current-password"]').fill(env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL('**/dashboard');
  const filesResponse = await context.request.get(base + '/api/files?projectId=' + latest.project.id);
  assert.equal(filesResponse.status(), 200);
  const files = (await filesResponse.json()).items; assert.ok(files.length);
  const file = files[0];
  const download = await context.request.get(base + '/api/files/' + file.id + '/download');
  assert.equal(download.status(), 200);
  const source = JSON.parse(decodeURIComponent(download.headers()['x-ufm-download-storage']));
  const bytes = await download.body();
  assert.equal(createHash('sha256').update(bytes).digest('hex'), file.checksum);
  assert.equal(source.strategy, 'CLOUD_PRIORITY');
  assert.ok(source.selected.provider !== 'LOCAL', 'existing ready cloud should serve this file');
  check('真实文件下载来源为云存储且 SHA256 正确', { fileId: file.id, source });
  const ranged = await context.request.get(base + '/api/files/' + file.id + '/download', { headers: { Range: 'bytes=2-5' } });
  assert.equal(ranged.status(), 206); assert.deepEqual(await ranged.body(), bytes.subarray(2, 6));
  assert.equal(JSON.parse(decodeURIComponent(ranged.headers()['x-ufm-download-storage'])).selected.configId, source.selected.configId);
  check('真实 Range 下载保留平台信息和正确字节');
  await navigate('/projects/' + latest.project.id);
  await page.getByRole('heading', { name: latest.project.name, exact: true }).waitFor();
  await page.getByText('优先下载：', { exact: false }).first().waitFor();
  const before = await page.evaluate(() => ({ header: document.querySelector('.admin-header').getBoundingClientRect().top, sidebar: document.querySelector('.admin-sidebar').getBoundingClientRect().top }));
  await page.locator('.admin-main').evaluate(el => { el.scrollTop = el.scrollHeight; });
  await page.getByRole('button', { name: '返回顶部', exact: true }).waitFor({ state: 'visible' });
  const after = await page.evaluate(() => ({ header: document.querySelector('.admin-header').getBoundingClientRect().top, sidebar: document.querySelector('.admin-sidebar').getBoundingClientRect().top, documentTop: document.scrollingElement.scrollTop, mainTop: document.querySelector('.admin-main').scrollTop }));
  assert.equal(after.header, before.header); assert.equal(after.sidebar, before.sidebar);
  assert.equal(after.documentTop, 0); assert.ok(after.mainTop > 240);
  check('桌面长页面仅内容滚动，左侧及头部固定', after);
  await screenshot('desktop-fixed-project');
  await page.getByRole('button', { name: '返回顶部', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.admin-main').scrollTop === 0);
  check('返回顶部按钮滚动正确的中间容器');
  await page.locator('.admin-main').evaluate(el => { el.scrollTop = 600; });
  await navigate('/files?projectId=' + latest.project.id);
  await page.locator('.data-table .el-table__body tbody tr').first().waitFor();
  assert.equal(await page.locator('.admin-main').evaluate(el => el.scrollTop), 0);
  check('切换页面重置中间内容滚动');
  const row = page.locator('.data-table .el-table__body tbody tr').filter({ hasText: file.originalName });
  await row.locator('.download-priority').waitFor();
  assert.match(await row.locator('.download-priority').innerText(), /优先下载：/);
  await row.getByRole('button', { name: '详情', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '文件详情' });
  await dialog.getByText('下载顺序：', { exact: false }).waitFor();
  assert.match(await dialog.innerText(), /本地.*兜底/);
  check('文件列表和详情分别显示优先平台、下载顺序及本地兜底');
  await screenshot('file-download-order');
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  const [browserDownload] = await Promise.all([page.waitForEvent('download'), row.getByRole('button', { name: '下载', exact: true }).click()]);
  await browserDownload.saveAs(path.join(out, 'downloaded-file.txt'));
  assert.deepEqual(fs.readFileSync(path.join(out, 'downloaded-file.txt')), bytes);
  const result = page.locator('.download-results');
  await result.getByText(source.selected.configName + '（', { exact: false }).first().waitFor();
  await result.getByText('本次实际下载来源', { exact: false }).waitFor();
  check('真实点击下载后显示实际云平台及尝试详情');
  await result.scrollIntoViewIfNeeded();
  await screenshot('actual-download-source');
  const historyResponse = await context.request.get(base + '/api/projects/' + latest.project.id + '/download-stats?fileId=' + file.id);
  const history = (await historyResponse.json()).items;
  assert.ok(history.some(item => item.message?.includes(source.selected.configName)));
  check('下载历史持久记录平台名称');
  await page.setViewportSize({ width: 320, height: 820 });
  await navigate('/projects/' + latest.project.id);
  await page.getByRole('heading', { name: latest.project.name, exact: true }).waitFor();
  await page.locator('.admin-main').evaluate(el => { el.scrollTop = el.scrollHeight; });
  await page.getByRole('button', { name: '返回顶部', exact: true }).waitFor({ state: 'visible' });
  const mobile = await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth, headerTop: document.querySelector('.admin-header').getBoundingClientRect().top, mainHeight: document.querySelector('.admin-main').clientHeight }));
  assert.ok(mobile.documentWidth <= mobile.width + 2); assert.equal(mobile.headerTop, 0); assert.ok(mobile.mainHeight > 300);
  check('320px 手机头部固定，中间可滚动且无整页横向溢出', mobile);
  await page.locator('.el-message').waitFor({ state: 'detached' });
  await screenshot('mobile-fixed-project');
  await page.getByRole('button', { name: '返回顶部', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.admin-main').scrollTop === 0);
  await page.locator('.mobile-menu-button').click();
  await page.getByRole('menuitem', { name: '文件管理', exact: true }).click();
  await page.waitForURL('**/files');
  check('手机返回顶部与左侧抽屉菜单可用');
  assert.deepEqual(errors, []); check('真实页面无未处理 JavaScript 异常');
} catch (error) { report.error = error.message.split('Call log:')[0].trim(); process.exitCode = 1; }
finally {
  report.sessionLoggedOut = !context;
  if (context) {
    try {
      const logout = await context.request.post(base + '/api/auth/logout', { data: {}, timeout: 10000 });
      assert.equal(logout.status(), 200);
      report.sessionLoggedOut = true;
    } catch { process.exitCode = 1; }
  }
  await browser?.close();
  report.counts = { passed: report.checks.length, failed: Number(Boolean(report.error)) + Number(!report.sessionLoggedOut) };
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ out, counts: report.counts, error: report.error, sessionLoggedOut: report.sessionLoggedOut }));
} })();
