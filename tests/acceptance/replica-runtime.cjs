const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..');
const env=Object.fromEntries(fs.readFileSync(path.join(root,'.env'),'utf8').split(/\r?\n/).filter(s=>/^\w+=/.test(s)).map(s=>{const i=s.indexOf('=');return [s.slice(0,i),s.slice(i+1).trim().replace(/^['"]|['"]$/g,'')];}));
require(path.join(root,'apps/api/dist/common/utils/database-url.util.js')).ensureDatabaseUrl(env);
Object.assign(process.env,env);
const {PrismaClient}=require('@prisma/client'),{ConfigService}=require('@nestjs/config');
const {StorageAdapterRegistry}=require(path.join(root,'apps/api/dist/storage/storage-registry.service.js'));
const {ReplicaService}=require(path.join(root,'apps/api/dist/storage/replica.service.js'));
const {StorageService}=require(path.join(root,'apps/api/dist/storage/storage.service.js'));
const make=name=>new (require(path.join(root,'apps/api/dist/storage/adapters/'+name+'.adapter.js'))[{'local':'LocalStorageAdapter','qiniu':'QiniuAdapter','upyun':'UpyunAdapter','s3':'S3Adapter','aliyun-oss':'AliyunOssAdapter'}[name]])();
const config=new ConfigService(env),db=new PrismaClient();
const registry=new StorageAdapterRegistry(make('aliyun-oss'),make('local'),make('qiniu'),make('s3'),make('upyun'));
module.exports={fs,path,root,env,db,config,registry,ReplicaService,StorageService};
